"""Act I of The Last Flame of Himavar (script.md, 0:00-0:40), made with
Google's Veo 3.1 through the Gemini API, the model behind Google Flow.

  1. Characters. Mira, Kaal and Elder Surya are drawn once each, as
     reference portraits, by a Gemini image model (act1/ref-*.png).
  2. Shots. Each of the six shots of Act I is generated by Veo 3.1 at
     1080p, 16:9, with sound: its own ambience, and the lines spoken in
     the voices the script gives. The portraits of the characters in a
     shot go with it as reference images, so they look the same from shot
     to shot. If the API refuses reference images, the shot is made from
     the prompt alone, which describes each character in the same words
     every time.
  3. Cut. The clips are trimmed to the script's timings (8+6+6+8+6+6 = 40
     seconds), cut together, and framed 2.39:1 between black bars, with a
     fade in and out, as a 1920 x 1080 film (act1.mp4).

A shot already made (act1/shot-N.mp4) is not made again, so a run that
stops can be started again; delete a clip to make a new take of it.

Free: clips made in Google Flow (flow-act1.md has the prompts) can be put
in act1/ as shot-1.mp4 ... shot-6.mp4 and cut without the API or a key:

    python3 media/fantasy-short/veo_act1.py cut

The key: requests to generativelanguage.googleapis.com need a Gemini API
key with billing on. In a Claude Code cloud session it is added as a
network secret (header x-goog-api-key) and sent by the proxy. Elsewhere,
set GEMINI_API_KEY. Veo 3.1 costs about $0.40 a second at 1080p, so one
take of all six shots is about $16; FAST=1 uses Veo 3.1 Fast (about $5).

    python3 media/fantasy-short/veo_act1.py
"""

import base64
import json
import os
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "act1"
API = "https://generativelanguage.googleapis.com/v1beta"
FAST = os.environ.get("FAST") == "1"

STYLE = ("Photoreal epic fantasy film, anamorphic lens, shallow depth of field, soft film grain, "
         "cold steel-blue moonlight, warm amber firelight, falling snow, breath vapour, volumetric light. "
         "Himalayan-inspired fantasy realm. No subtitles, no on-screen text.")

CHARACTERS = {
    "mira": ("Mira, a 19-year-old female warden: slim, determined, warm brown skin, dark hair in a single "
             "braid with a copper ring, a small ash mark on her forehead, a layered crimson wool robe with "
             "brass clasps, a fur-lined grey cloak, worn leather gloves, holding a small brass lantern "
             "with a tiny golden flame"),
    "kaal": ("Kaal, a 45-year-old disgraced guardian: tall and broad, grey-streaked beard, the sides of "
             "his head shaved, a scar through his left eyebrow, tired eyes, dented dark-iron armour plates "
             "over a long worn black coat, a heavy iron shackle on his right wrist with a broken chain "
             "hanging from it, a broad curved blade at his side"),
    "elder": ("Elder Surya, a monk in his seventies: long white beard, saffron and gold robes, a wooden "
              "staff topped with a dark, empty lamp"),
}

# (seconds generated, seconds kept, characters, prompt)
SHOTS = [
    (8, 8, [], "Slow aerial drone shot gliding forward over a vast moonlit valley of snow peaks at night. "
     "Terraced stone villages on the slopes, every window dark. A frozen river winds like a silver thread. "
     "Thin clouds drift across a huge full moon. Audio: howling wind and a deep, distant horn. "
     "A deep, slow old man's voice-over says: \"Every winter, the Sky Lamp keeps the dark from our door.\""),
    (6, 6, [], "A giant bronze brazier the size of a house stands alone on a snowy mountain summit at "
     "night, carved with sun runes, frost creeping over the runes, stars behind it. The last embers in its "
     "bowl fade to grey and the wind tears away a final curl of smoke. Slow crane shot up from the frosted "
     "runes to the dying embers. Audio: wind. A deep, slow old man's voice-over says: \"Tonight... it went out.\""),
    (6, 6, [], "A mountain village of stone houses half-buried in snow at night, rune banners frozen stiff "
     "on poles. At a small wooden window a mother pulls her young daughter back from the glass. Behind "
     "them, at the black edge of a pine forest, pairs of glowing ember-red eyes open one by one in the "
     "darkness. The camera pushes in past the window towards the eyes. Audio: wind chimes clinking, then "
     "a low growl."),
    (8, 8, ["elder", "mira"], "Inside a vast stone monastery hall at night, hundreds of unlit bronze lamps "
     "on stepped shelves rise into darkness. A single shaft of moonlight falls through a high window, dust "
     "and snow drifting in the beam; monks in grey robes stand silent along the walls. {elder} lifts a "
     "small brass lantern holding one tiny golden flame, the only warm light in the hall. {mira} kneels "
     "before him. Slow dolly in, low angle. The elder says in a deep, grave voice: \"This is the last fire "
     "of Himavar. Carry it to the summit before dawn.\""),
    (6, 6, ["mira"], "Extreme close-up of {mira}, kneeling in a dark stone hall. The tiny golden flame of "
     "the lantern is reflected in her eyes and its warm glow lights her face; her breath clouds in the "
     "cold. Darkness behind her, softly out of focus. She says quietly: \"Alone?\""),
    (6, 6, ["kaal", "elder"], "In a vast dark stone hall lined with unlit bronze lamps, great iron-studded "
     "doors grind open and snow blows in. {kaal} walks in towards the camera, his shackle chain dragging "
     "and ringing on the stone floor; monks in grey robes turn and whisper. A deep, grave old man's voice "
     "says from off screen: \"No. With the man who let it die.\" Audio: grinding doors, wind, the chain on stone."),
]
SCOPE = 2.39                       # picture aspect between the bars


def request(method, url, body=None, raw=False):
    headers = {"Content-Type": "application/json"}
    if os.environ.get("GEMINI_API_KEY"):
        headers["x-goog-api-key"] = os.environ["GEMINI_API_KEY"]
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=300) as r:
            out = r.read()
    except urllib.error.HTTPError as e:
        raise RuntimeError(f"{e.code} {e.reason}: {e.read().decode(errors='replace')[:800]}") from None
    return out if raw else json.loads(out)


def pick_models():
    names = [m["name"].split("/")[-1] for m in request("GET", f"{API}/models?pageSize=1000")["models"]]
    veo = [n for n in names if n.startswith("veo-3.1") and ("fast" in n) == FAST and "lite" not in n]
    image = [n for n in names if "image" in n and n.startswith("gemini")]
    if not veo or not image:
        sys.exit(f"no Veo 3.1 or Gemini image model on this key; models: {names}")
    return sorted(veo)[-1], sorted(image)[-1]


def portrait(model, key):
    path = OUT / f"ref-{key}.png"
    if path.exists():
        return path
    prompt = (f"Full-body character reference portrait of {CHARACTERS[key]}. Standing, facing the camera, "
              f"plain neutral grey studio background, soft even light. {STYLE}")
    res = request("POST", f"{API}/models/{model}:generateContent",
                  {"contents": [{"parts": [{"text": prompt}]}],
                   "generationConfig": {"responseModalities": ["IMAGE"]}})
    for part in res["candidates"][0]["content"]["parts"]:
        if "inlineData" in part:
            path.write_bytes(base64.b64decode(part["inlineData"]["data"]))
            print(f"  drew {path.name}")
            return path
    sys.exit(f"no image for {key}: {json.dumps(res)[:500]}")


def shot(model, n, seconds, chars, text, refs):
    path = OUT / f"shot-{n}.mp4"
    if path.exists():
        print(f"  shot {n}: already made")
        return path
    prompt = text.format(**{k: CHARACTERS[k] for k in CHARACTERS}) + " " + STYLE
    params = {"aspectRatio": "16:9", "resolution": "1080p", "durationSeconds": seconds,
              "personGeneration": "allow_adult"}
    instance = {"prompt": prompt}
    if chars:
        instance["referenceImages"] = [
            {"image": {"bytesBase64Encoded": base64.b64encode(refs[c].read_bytes()).decode(), "mimeType": "image/png"},
             "referenceType": "asset"} for c in chars]
    url = f"{API}/models/{model}:predictLongRunning"
    try:
        op = request("POST", url, {"instances": [instance], "parameters": params})
    except RuntimeError as e:
        if not chars:
            raise
        print(f"  shot {n}: reference images refused ({str(e)[:120]}); from the prompt alone")
        instance.pop("referenceImages")
        op = request("POST", url, {"instances": [instance], "parameters": params})
    print(f"  shot {n}: generating ({seconds} s)", end="", flush=True)
    while not op.get("done"):
        time.sleep(10)
        print(".", end="", flush=True)
        op = request("GET", f"{API}/{op['name']}")
    print()
    if "error" in op:
        sys.exit(f"shot {n} failed: {op['error']}")
    samples = op["response"]["generateVideoResponse"]["generatedSamples"]
    path.write_bytes(request("GET", samples[0]["video"]["uri"], raw=True))
    return path


def cut(clips):
    """Trim to the script's timings, cut together, and frame 2.39:1 between
    bars, with a fade in and out."""
    inputs, chain = [], []
    bar = round((1080 - 1920 / SCOPE) / 2)
    for i, (clip, (_, keep, _, _)) in enumerate(zip(clips, SHOTS)):
        inputs += ["-i", str(clip)]
        chain.append(f"[{i}:v]trim=0:{keep},setpts=PTS-STARTPTS,scale=1920:1080,fps=24,format=yuv420p,setsar=1[v{i}]")
        chain.append(f"[{i}:a]atrim=0:{keep},asetpts=PTS-STARTPTS,aresample=48000,"
                     f"aformat=channel_layouts=stereo,apad=whole_dur={keep}[a{i}]")
    pairs = "".join(f"[v{i}][a{i}]" for i in range(len(clips)))
    total = sum(s[1] for s in SHOTS)
    chain.append(f"{pairs}concat=n={len(clips)}:v=1:a=1[vc][ac]")
    chain.append(f"[vc]drawbox=x=0:y=0:w=iw:h={bar}:color=black:t=fill,"
                 f"drawbox=x=0:y=ih-{bar}:w=iw:h={bar}:color=black:t=fill,"
                 f"fade=t=in:d=0.8,fade=t=out:st={total - 0.8}:d=0.8[vout]")
    chain.append(f"[ac]afade=t=in:d=0.8,afade=t=out:st={total - 0.8}:d=0.8[aout]")
    out = HERE / "act1.mp4"
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", *inputs, "-filter_complex", ";".join(chain),
                    "-map", "[vout]", "-map", "[aout]", "-c:v", "libx264", "-crf", "17", "-preset", "slow",
                    "-c:a", "aac", "-b:a", "192k", "-movflags", "+faststart", str(out)], check=True)
    print(f"wrote {out.name} ({total} s)")


def main():
    OUT.mkdir(exist_ok=True)
    if sys.argv[1:] == ["cut"]:
        clips = [OUT / f"shot-{n}.mp4" for n in range(1, len(SHOTS) + 1)]
        missing = [c.name for c in clips if not c.exists()]
        if missing:
            sys.exit(f"missing in {OUT}: {', '.join(missing)}")
        cut(clips)
        return
    veo, image = pick_models()
    print(f"models: {veo}, {image}")
    refs = {k: portrait(image, k) for k in CHARACTERS}
    clips = [shot(veo, n, s, c, p, refs) for n, (s, _, c, p) in enumerate(SHOTS, 1)]
    cut(clips)


if __name__ == "__main__":
    main()
